namespace ekphore::dstortion {

// six floats then a bool, no names for them yet
struct Parameters {
    std::array<float, 6> primary{};
    bool mono_mode{};
};

class Processor {
  public:
    void configure(std::uint32_t sample_rate, const Parameters &parameters);
    void reset();
    // call BEFORE the samples, otherwise every sample is its own span
    void begin_span(std::size_t frames);
    [[nodiscard]] std::pair<float, float> process(float left, float right);

  private:
    friend struct ProcessorInspection;
    using Lanes = std::array<float, 4>;
    struct ChannelState {
        Lanes input_history{};
        std::array<Lanes, 3> shaped_history{};
        Lanes input{};
        Lanes input_filter{};
        Lanes output_filter{};
    };
    void on_control_rate();
    void prepare_chunk();
    [[nodiscard]] float table_lookup(float coordinate) const;
    [[nodiscard]] float process_channel(float input, std::size_t channel);

    Parameters settings{};
    std::uint32_t processing_rate{ 44100 };
    std::array<float, 8> targets{};
    std::array<float, 8> currents{};
    std::array<float, 8> increments{};
    Lanes input_filters{};
    Lanes output_filters{};
    std::array<std::array<float, 2>, 256> shaper_table{};
    float table_bias{};
    float table_lower{};
    float increment_scale{};
    std::uint32_t control_ticks{};
    std::int64_t ramp_ticks_remaining{};
    std::size_t span_remaining{};
    std::size_t chunk_remaining{};
    std::size_t control_countdown{};
    bool configured{};
    bool coefficients_dirty{};
    std::array<ChannelState, 2> states{};
};

} // namespace ekphore::dstortion

