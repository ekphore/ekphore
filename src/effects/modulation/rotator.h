namespace ekphore::rotator {
struct Parameters {
    float speed{};
    float balance{ 0.5F };
    float acceleration_high{ 0.3F };
    float acceleration_low{ 0.2F };
    float distance{ 0.3F };
    float mix{ 1.0F };
};

class Processor {
  public:
    Processor() = default;
    // what reset goes back to
    explicit Processor(const Parameters &initial_parameters)
        : startup_params(initial_parameters) {}
    void configure(std::uint32_t sample_rate, const Parameters &parameters);
    // once per span, BEFORE the samples
    void begin_span(std::size_t frames);
    // rotor state stays
    void reset();
    [[nodiscard]] std::pair<float, float> process(float left, float right);

  private:
    friend struct StartupInspection;
    static constexpr std::size_t ring_size = 512;
    static constexpr std::size_t ring_mask = ring_size - 1;
    using Vector = std::array<float, 4>;
    [[nodiscard]] static float exp_table(float position);
    [[nodiscard]] static float leslie(float phase);
    [[nodiscard]] static float read_delay(
            const std::array<float, ring_size> &ring, std::size_t write_index,
            float delay_samples);
    void update_control();
    void set_sample_rate(std::uint32_t sample_rate);

    Parameters params{};
    std::optional<Parameters> startup_params;
    std::uint32_t sampling_rate{};
    std::size_t write_pos{};
    std::array<float, ring_size> horn_ring{}, bass_ring{};
    float split_low{}, split_band{}, split_f{}, split_d{};
    std::array<float, 2> resonator_low{}, resonator_band{}, resonator_f{},
            resonator_d{};
    Vector horn{}, horn_step{}, horn_depth{}, horn_depth_step{};
    Vector bass{}, bass_step{}, bass_depth{}, bass_depth_step{};
    Vector horn_band{}, horn_low{}, horn_f{}, horn_f_depth{};
    Vector lfo{}, lfo_step{};
    float milliseconds{}, rotor_decrement{}, lfo_scale{};
    float high_speed{}, low_speed{}, high_phase{}, low_phase{};
    float high_target{ 0.7920000553131104F }, low_target{ 0.6480000019073486F };
    float control_accumulator{}, high_acceleration{}, low_acceleration{};
    float mix_current{}, mix_step{}, ramp_step{};
    int ramp_blocks{}, mix_remaining{}, coefficient_remaining{};
    std::size_t span_remaining{}, host_remaining{}, control_remaining{};
    bool speed_fast{}, mix_dirty{};
};
} // namespace ekphore::rotator

